// Package clipboard writes secrets to the macOS pasteboard, marked as
// concealed/transient so clipboard managers (including Alfred's clipboard
// history) don't record them.
package clipboard

import (
	"bytes"
	"fmt"
	"os/exec"
	"strings"
)

// The secret is read from stdin so it never appears in the process list.
const copyScript = `
ObjC.import('AppKit');
function run() {
  var data = $.NSFileHandle.fileHandleWithStandardInput.readDataToEndOfFile;
  var str = $.NSString.alloc.initWithDataEncoding(data, $.NSUTF8StringEncoding);
  var pb = $.NSPasteboard.generalPasteboard;
  pb.clearContents;
  pb.setStringForType(str, $.NSPasteboardTypeString);
  pb.setStringForType($(''), 'org.nspasteboard.ConcealedType');
  pb.setStringForType($(''), 'org.nspasteboard.TransientType');
  pb.setStringForType($(''), 'org.nspasteboard.AutoGeneratedType');
}
`

// Copy places value on the clipboard.
func Copy(value string) error {
	cmd := exec.Command("/usr/bin/osascript", "-l", "JavaScript", "-e", copyScript)
	cmd.Stdin = strings.NewReader(value)
	var stderr bytes.Buffer
	cmd.Stderr = &stderr
	if err := cmd.Run(); err != nil {
		return fmt.Errorf("copy to clipboard: %s: %w", strings.TrimSpace(stderr.String()), err)
	}
	return nil
}
